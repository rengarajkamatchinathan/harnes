export type MsgKey = keyof typeof en;
const dict: Record<string, string> = en;

export function t(key: MsgKey, vars?: Record<string, string | number>): string {
  const s = dict[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`)) : s;
}

const rules = new Intl.PluralRules("en");
export function plural(n: number, forms: { one: string; other: string }): string {
  return (rules.select(n) === "one" ? forms.one : forms.other).replace("#", String(n));
}

export function formatCost(usd: number): string {
  return usd < 0.01 && usd > 0 ? `<$0.01` : `$${usd.toFixed(2)}`;
}

export function formatTokens(n: number): string {
  return n >= 1000 ? `${(n / 1000).toFixed(n >= 10000 ? 0 : 1)}k` : String(n);
}
